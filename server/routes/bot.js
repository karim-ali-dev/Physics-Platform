function findKb(msg) {
  let best = null;
  let bestScore = 0;
  for (const e of KB) {
    let score = 0;
    for (const w of e.k) {
      const kw = norm(w);
      if (kw && msg.includes(kw)) score += kw.length;
    }
    if (score > bestScore) {
      bestScore = score;
      best = e;
    }
  }
  return bestScore >= 3 ? best : null;
}

/* ============================================================
   آلة حساب التعبيرات الرياضية (آمنة — بدون eval)
   ============================================================ */
function evalMath(expr) {
  const s = String(expr)
    .replace(/[٠-٩]/g, (d) => '٠١٢٣٤٥٦٧٨٩'.indexOf(d))
    .replace(/[أ-ي]/g, '')
    .replace(/×/g, '*')
    .replace(/÷/g, '/')
    .replace(/−/g, '-')
    .replace(/[.,]/g, '.')
    .toLowerCase()
    .replace(/\s+/g, '');
  if (!s || !/[0-9]/.test(s)) return null;
  let i = 0;

  function peek() { return s[i]; }
  function eat(ch) { if (s[i] === ch) { i++; return true; } return false; }
  function num() {
    if (s.startsWith('pi', i)) { i += 2; return Math.PI; }
    const m = s.slice(i).match(/^\d+(\.\d+)?/);
    if (m) { i += m[0].length; return parseFloat(m[0]); }
    return NaN;
  }
  function factor() {
    if (eat('(')) { const v = add(); eat(')'); return v; }
    if (eat('-')) return -factor();
    const n = num();
    if (!Number.isNaN(n)) return n;
    const fn = ['sin', 'cos', 'tan', 'sqrt', 'log', 'ln', 'abs'].find((f) => s.startsWith(f, i));
    if (fn) {
      i += fn.length;
      const v = factor();
      switch (fn) {
        case 'sin': return Math.sin(v);
        case 'cos': return Math.cos(v);
        case 'tan': return Math.tan(v);
        case 'sqrt': return Math.sqrt(v);
        case 'log': return Math.log10(v);
        case 'ln': return Math.log(v);
        default: return Math.abs(v);
      }
    }
    throw new Error('expr');
  }
  function pow() {
    let v = factor();
    while (s[i] === '^' || s.slice(i, 3) === '**') {
      if (s[i] === '^') { i++; v = Math.pow(v, pow()); }
      else { i += 2; v = Math.pow(v, pow()); }
    }
    return v;
  }
  function mul() {
    let v = pow();
    while (s[i] === '*' || s[i] === '/') {
      if (eat('*')) v *= pow();
      else { eat('/'); v /= pow(); }
    }
    return v;
  }
  function add() {
    let v = mul();
    while (s[i] === '+' || s[i] === '-') {
      if (eat('+')) v += mul();
      else { eat('-'); v -= mul(); }
    }
    return v;
  }

  const result = add();
  if (s[i]) throw new Error('expr');
  if (!Number.isFinite(result)) throw new Error('inf');
  return result;
}

