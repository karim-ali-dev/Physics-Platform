function convertUnits(msg) {
  const m = msg.match(/[-+]?\d+(\.\d+)?/);
  if (!m) return null;
  const val = parseFloat(m[0]);
  const lower = norm(msg).toLowerCase();
  const tokens = lower.split(/\s+/).map((t) => t.replace(/^[-+]?\d+(\.\d+)?/, ''));
  const found = [];
  for (const tok of tokens) {
    if (!tok) continue;
    for (const u of UNITS) {
      if (found.some((x) => x === u)) continue;
      if (u.a.some((a) => norm(a) === tok) || u.l.some((l) => l === tok)) found.push(u);
    }
  }
  if (found.length < 2) return null;
  const first = found[0];
  const last = found[found.length - 1];
  if (first.b !== last.b) return null;
  const result = (val * first.f) / last.f;
  const rounded = Math.round(result * 1000) / 1000;
  const r = Math.abs(result) >= 1e9 || (Math.abs(result) < 0.001 && result !== 0) ? result.toExponential(4) : rounded.toLocaleString('en-US');
  return `${val} ${first.a[0]} = ${r} ${last.a[0]}`;
}

