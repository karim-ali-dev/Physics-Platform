async function loadSchedule() {
  return db.all('SELECT grade, day, start_time, end_time, note, period, tag, tag_active FROM schedule_items WHERE active = 1 ORDER BY sort_order ASC, id ASC');
}

function periodIcon(p) {
  return p === 'الليل' ? '🌙' : p === 'النهار' ? '☀️' : '';
}

function sessionText(r) {
  const icon = periodIcon(r.period);
  const tag = r.tag && r.tag_active !== 0 ? ` 🔖 ${r.tag}` : '';
  return `${icon ? icon + ' ' : ''}${r.start_time}${r.end_time ? ' حتى ' + r.end_time : ''}${tag}${r.note ? ' — ' + r.note : ''}`;
}

function gradeScheduleText(grade, items) {
  const rows = items.filter((s) => s.grade === grade);
  if (!rows.length) return null;
  const byDay = {};
  rows.forEach((r) => { (byDay[r.day] = byDay[r.day] || []).push(r); });
  const lines = Object.keys(byDay)
    .sort((a, b) => DAY_ORDER.indexOf(a) - DAY_ORDER.indexOf(b))
    .map((d) => {
      const times = byDay[d].map(sessionText).join('\n');
      return `📅 ${d}:\n${times}`;
    });
  return lines.join('\n');
}

function fullScheduleText(items) {
  const byDay = {};
  items.forEach((r) => { (byDay[r.day] = byDay[r.day] || []).push(r); });
  const lines = DAY_ORDER.filter((d) => byDay[d]).map((d) => {
    const rows = byDay[d].map((r) => `• ${r.grade}: ${sessionText(r)}`).join('\n');
    return `📅 ${d}:\n${rows}`;
  });
  return lines.join('\n');
}

